// Encode values so student text cannot close a context field and forge another.
const field = (name, value) => `<${name}>${JSON.stringify(value ?? '').replaceAll('<', '\\u003c').replaceAll('>', '\\u003e')}</${name}>`;

export function buildPrompt(session, problem, text, assessmentPoints = '') {
  return {
    systemPrompt: [rules,
      field('题目', { title: problem.title, description: problem.description, input: problem.input, output: problem.output, language: problem.language === 'cpp' ? 'C++17 / main.cpp' : 'C11 / main.c' }),
      field('考点', assessmentPoints),
      field('公开样例', { 输入: problem.sampleInput, 期望输出: problem.sampleOutput }),
    ].join('\n'),
    prompt: [
      field('规划文档', session.plan),
      field('当前代码', session.code),
      field('运行结果', session.lastRun),
      field('历史对话', session.chats),
      field('学生本次请求', text),
    ].join('\n'),
  };
}
