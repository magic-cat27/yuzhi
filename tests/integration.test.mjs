import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtemp, rm, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

test('考核主线：门控、规划版本、C 编译运行、轨迹、结束只读', { timeout: 20000 }, async () => {
  const dir = await mkdtemp(join(tmpdir(), 'yuzhi-test-'));
  const port = 3197;
  const server = spawn(process.execPath, ['server.mjs'], { env: { ...process.env, PORT: String(port), DATA_DIR: dir, DEEPSEEK_API_KEY: '', DASHSCOPE_API_KEY: '', DEFAULT_AI_MODEL: 'qwen3.7-plus' }, stdio: ['ignore', 'pipe', 'pipe'] });
  try {
    await new Promise((resolve, reject) => { server.stdout.on('data', b => { if (b.toString().includes('已启动')) resolve(); }); server.once('exit', c => reject(new Error(`Server exited ${c}`))); server.once('error', reject); });
    let cookie = '';
    const api = async (path, value) => { const r = await fetch(`http://127.0.0.1:${port}/api/${path}`, { headers: { Cookie: cookie }, ...(value === undefined ? {} : { method: 'POST', body: JSON.stringify(value) }) }); if (r.headers.get('set-cookie')) cookie = r.headers.get('set-cookie').split(';')[0]; return { status: r.status, value: await r.json() }; };
    const review = await fetch(`http://127.0.0.1:${port}/code-review.js`);
    assert.equal(review.status, 200);
    assert.match(await review.text(), /export function reviewCode/);
    assert.equal((await api('status')).value.pi, true);
    assert.equal((await api('status')).value.model, 'qwen3.7-plus');
    assert.equal((await api('status')).value.models.length, 7);
    assert.equal((await api('teacher/records')).status, 403);
    assert.equal((await api('teacher/trash')).status, 403);
    assert.equal((await api('teacher/trash', { ids: [] })).status, 403);
    assert.equal((await api('teacher/restore', { ids: [] })).status, 403);
    assert.equal((await api('sessions', { problemId: 'dijkstra' })).status, 403);
    await api('role', { role: 'student' });
    assert.equal((await api('teacher/records')).status, 403);
    assert.equal((await api('teacher/trash')).status, 403);
    assert.equal((await api('teacher/trash', { ids: [] })).status, 403);
    assert.equal((await api('teacher/restore', { ids: [] })).status, 403);
    const catalog = (await api('problems')).value;
    assert.equal(catalog[0].id, 'expression');
    assert.equal(catalog.filter(p => p.course === 'C语言程序设计与实验').length, 10);
    assert.ok(!JSON.stringify(catalog).includes('判定要点：'));
    const expressionSession = (await api('sessions', { problemId: 'expression' })).value;
    assert.equal(expressionSession.problemId, 'expression');
    assert.equal(expressionSession.plan, '');
    assert.equal(catalog.filter(p => p.course === '数据结构与算法').length, 4);
    assert.equal(catalog.length, 48);
    const sets = (await api('problem-sets')).value;
    assert.equal(sets.length, 13);
    assert.ok(!JSON.stringify(sets).includes('判定要点：'));
    assert.equal((await api('src/assessment-points.mjs')).status, 404);
    assert.equal((await fetch(`http://127.0.0.1:${port}/core-problems.mjs`)).status, 404);
    const cpp = (await api('sessions', { problemId: 'rational-class' })).value;
    assert.ok(cpp.code.includes('<iostream>'));
    const cppCode = '#include <iostream>\nclass Number { int n; public: Number(int v):n(v){} int value() const {return n;} };\nint main(){ int n; std::cin >> n; std::cout << Number(n).value() << "\\n"; }';
    const cppRun = (await api(`sessions/${cpp.id}/run`, { code: cppCode, stdin: '42', language: 'c' })).value;
    assert.equal(cppRun.lastRun.stdout, '42\n');
    assert.equal(cppRun.lastRun.exitCode, 0);
    const algorithmSession = (await api('sessions', { problemId: 'dijkstra' })).value;
    assert.equal(algorithmSession.problemId, 'dijkstra');
    assert.equal(algorithmSession.versions.length, 0);
    let s = (await api('sessions', { problemId: 'scheduler' })).value;
    const endpoint = `sessions/${s.id}`;
    assert.equal(s.plan, '');
    assert.equal((await api(endpoint + '/chat', { text: '替我规划' })).status, 400);
    assert.equal((await api(endpoint + '/plan', { text: '   ' })).status, 400);
    s = (await api(endpoint + '/plan', { text: '独立规划第一版' })).value;
    assert.equal(s.versions.length, 1);
    s = (await api(endpoint + '/plan', { text: '独立规划第二版，补全边界' })).value;
    assert.equal(s.versions.length, 2);
    assert.equal(s.versions[0].text, '独立规划第一版');
    assert.equal((await api(endpoint + '/chat', { text: '按规划实现' })).status, 503);
    assert.equal((await api(endpoint + '/chat', { text: '执行', model: 'untrusted-model' })).status, 400);
    const code = '#include <stdio.h>\nint main(void){int a,b;if(scanf("%d%d",&a,&b)==2)printf("%d\\n",a+b);return 0;}';
    s = (await api(endpoint + '/run', { code, stdin: '17 25' })).value;
    assert.equal(s.lastRun.stdout, '42\n'); assert.equal(s.lastRun.exitCode, 0);
    s = (await api(endpoint + '/run', { code: 'this is not valid C', stdin: '' })).value;
    assert.equal(s.lastRun.stage, 'compile'); assert.notEqual(s.lastRun.exitCode, 0);
    s = (await api(endpoint + '/run', { code: 'int main(void){while(1){}return 0;}', stdin: '' })).value;
    assert.equal(s.lastRun.stopped, true);
    s = (await api(endpoint + '/code', { code, source: 'ai' })).value;
    assert.equal(s.events, undefined);
    assert.equal((await api(endpoint + '/export')).status, 403);
    const forbidden = await fetch(`http://127.0.0.1:${port}/api/${endpoint}/plan`, { method: 'POST', headers: { Origin: 'https://other.example' }, body: JSON.stringify({ text: 'cross site' }) });
    assert.equal(forbidden.status, 403);
    s = (await api(endpoint + '/end', {})).value;
    assert.ok(s.endedAt);
    for (const action of ['plan', 'code', 'run', 'chat']) assert.equal((await api(endpoint + '/' + action, {})).status, 409);
    assert.equal((await api(endpoint)).value.code, code);
    const record = JSON.parse(await readFile(join(dir, 'index.json'), 'utf8')).find(r => r.id === s.id);
    const events = (await readFile(join(dir, record.path, 'events.jsonl'), 'utf8')).trim().split('\n').map(JSON.parse);
    assert.equal(events[0].type, 'session_start'); assert.equal(events.at(-1).type, 'session_end');
    assert.equal(new Set(events.map(e => e.event_id)).size, events.length);
    await api('role', { role: 'student' });
    assert.equal((await api(endpoint)).status, 403);
    await api('role', { role: 'teacher' });
    assert.ok((await api('teacher/records')).value.some(r => r.id === s.id));
    assert.equal((await api(endpoint + '/code', { code })).status, 403);
    assert.equal((await api(endpoint)).value.events.length, events.length);
    const exported = await fetch(`http://127.0.0.1:${port}/api/${endpoint}/export`, { headers: { Cookie: cookie } });
    assert.equal((await exported.text()).trim().split('\n').length, events.length);
    assert.equal((await api('teacher/trash', { ids: ['../../bad'] })).status, 400);
    assert.equal((await api('teacher/trash', { ids: [] })).status, 400);
    assert.equal((await api('teacher/trash', { ids: [s.id, expressionSession.id] })).value.count, 2);
    assert.equal((await api(endpoint)).status, 404);
    assert.ok(!(await api('teacher/records')).value.some(r => r.id === s.id));
    assert.equal((await api('teacher/trash')).value.length, 2);
    assert.equal((await api('teacher/restore', { ids: [s.id, expressionSession.id] })).value.count, 2);
    assert.equal((await api('teacher/trash')).value.length, 0);
    assert.equal((await api(endpoint)).value.events.length, events.length);

  } finally { server.kill(); await rm(dir, { recursive: true, force: true }); }
});
